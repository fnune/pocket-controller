#!/usr/bin/env python3
import argparse
import filecmp
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERIC = ROOT / "screen" / "assets"
DEVICES = ROOT / "screen" / "devices"
DEVICE_OUTPUT = GENERIC / "devices"
FONT = ROOT / "screen" / "fonts" / "rounded-mplus-1c-bold-subset.ttf"
SVG = "http://www.w3.org/2000/svg"
XLINK = "http://www.w3.org/1999/xlink"
ALIGNMENTS = {"left", "center", "right"}

ET.register_namespace("", SVG)
ET.register_namespace("xlink", XLINK)


def render(source: Path, target: Path) -> None:
    subprocess.run(
        ["resvg", "--use-font-file", str(FONT), "--skip-system-fonts", str(source), str(target)],
        check=True,
    )


def number(element: ET.Element, name: str) -> int:
    value = element.get(name)
    if value is None or not value.lstrip("-").isdigit():
        raise SystemExit(f"{element.get('id')}: {name} must be a whole number, got {value!r}")
    return int(value)


def standalone(layer: ET.Element) -> ET.Element:
    copy = ET.Element(f"{{{SVG}}}svg")
    for name in ("width", "height", "viewBox"):
        if layer.get(name) is None:
            raise SystemExit(f"layer {layer.get('id')}: missing {name}")
        copy.set(name, layer.get(name))
    copy.extend(list(layer))
    return copy


def build_device(source: Path, output: Path, scratch: Path) -> None:
    tree = ET.parse(source)
    lines = []
    for child in tree.getroot():
        identifier = child.get("id")
        if child.tag == f"{{{SVG}}}svg" and identifier:
            layer_source = scratch / f"{identifier}.svg"
            ET.ElementTree(standalone(child)).write(layer_source, encoding="unicode")
            render(layer_source, output / f"{identifier}.png")
            lines.append(f"image {identifier} {number(child, 'x')} {number(child, 'y')}")
        elif child.tag == f"{{{SVG}}}g" and identifier == "anchors":
            for point in child:
                name = point.get("id")
                x, y = number(point, "cx"), number(point, "cy")
                if name is None:
                    raise SystemExit(f"{source.name}: an anchor has no id")
                if name.startswith("stick-"):
                    lines.append(f"stick {name.removeprefix('stick-')} {x} {y} {number(point, 'r')}")
                else:
                    align = point.get("data-align", "left")
                    if align not in ALIGNMENTS:
                        raise SystemExit(f"{name}: data-align must be one of {sorted(ALIGNMENTS)}")
                    lines.append(f"anchor {name} {x} {y} {align}")
        else:
            raise SystemExit(f"{source.name}: unexpected top-level element {child.tag} {identifier!r}")
    (output / "manifest").write_text("\n".join(lines) + "\n")


def build(target: Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    for source in sorted(GENERIC.glob("*.svg")):
        render(source, target / f"{source.stem}.png")
    with tempfile.TemporaryDirectory() as scratch:
        for source in sorted(DEVICES.glob("*.svg")):
            output = target / "devices" / source.stem
            output.mkdir(parents=True, exist_ok=True)
            build_device(source, output, Path(scratch))


def generated(directory: Path) -> set[Path]:
    files = {path.relative_to(directory) for path in directory.glob("*.png")}
    devices = directory / "devices"
    if devices.exists():
        files |= {path.relative_to(directory) for path in devices.rglob("*") if path.is_file()}
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description="Render screen assets and device manifests from their SVG sources")
    parser.add_argument("--check", action="store_true", help="fail if the committed output is stale")
    arguments = parser.parse_args()
    if not arguments.check:
        shutil.rmtree(DEVICE_OUTPUT, ignore_errors=True)
        for stale in GENERIC.glob("*.png"):
            stale.unlink()
        build(GENERIC)
        return 0
    with tempfile.TemporaryDirectory() as fresh:
        fresh_root = Path(fresh)
        build(fresh_root)
        expected, actual = generated(fresh_root), generated(GENERIC)
        problems = [f"missing: {path}" for path in sorted(expected - actual)]
        problems += [f"not generated by any source: {path}" for path in sorted(actual - expected)]
        problems += [
            f"stale: {path}"
            for path in sorted(expected & actual)
            if not filecmp.cmp(fresh_root / path, GENERIC / path, shallow=False)
        ]
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print("run `just assets` and commit the result", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
